CREATE TABLE IF NOT EXISTS public.study_subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 80),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, name),
    UNIQUE (user_id, id)
);

CREATE TABLE IF NOT EXISTS public.study_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    subject_id BIGINT NOT NULL,
    topic TEXT NOT NULL CHECK (char_length(btrim(topic)) BETWEEN 1 AND 120),
    session_date DATE NOT NULL,
    start_time TIME,
    estimated_minutes INTEGER NOT NULL DEFAULT 30
        CHECK (estimated_minutes BETWEEN 1 AND 600),
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (user_id, subject_id)
        REFERENCES public.study_subjects(user_id, id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS study_sessions_user_date_idx
    ON public.study_sessions (user_id, session_date, start_time);

ALTER TABLE public.study_subjects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_sessions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users manage their own study subjects" ON public.study_subjects;
CREATE POLICY "Users manage their own study subjects"
    ON public.study_subjects
    FOR ALL
    TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users manage their own study sessions" ON public.study_sessions;
CREATE POLICY "Users manage their own study sessions"
    ON public.study_sessions
    FOR ALL
    TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

GRANT SELECT, INSERT, UPDATE, DELETE
    ON public.study_subjects, public.study_sessions
    TO authenticated;

GRANT USAGE, SELECT
    ON SEQUENCE public.study_subjects_id_seq, public.study_sessions_id_seq
    TO authenticated;
